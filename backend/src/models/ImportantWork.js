const mongoose = require('mongoose');

const importantWorkSchema = new mongoose.Schema({
  boardGroup:{type:String,enum:['Today Urgent','Main Campaign','Tomorrow','WIP'],default:'WIP'},
  briefData:{type:Buffer,select:false},
  briefName:{type:String,default:'',maxlength:180},
  briefMime:{type:String,default:''},
  businessUnit:{type:String,enum:['Bank','Pay','Comms'],default:'Bank'},
  businessHeadEmail:{type:String,default:''},
  bpEmail:{type:String,default:''},
  sentAt:Date, sentBy:{type:mongoose.Schema.Types.ObjectId,ref:'User'},
  designerEmail: {type:String,default:'',lowercase:true},
  merchandisingEmail: {type:String,default:'',lowercase:true},
  designType: { type: String, enum: ['Social', 'Print', 'Video & Photography', 'Other'], default: 'Print' },
  designDriveUrl: { type: String, default: '', maxlength: 2000 },
  printDestination:{type:String,enum:['Production','Supplier'],default:'Production'},
  supplierName:{type:String,default:'',maxlength:160},
  revisionNote:{type:String,default:'',maxlength:2000},
  revisionSubmittedAt:Date,
  bpEmailMessageId:String,
  designChecked: {type:Boolean,default:false},
  designChecks:[{_id:false,slot:{type:String,enum:['Art Director','Designer']},actor:{type:mongoose.Schema.Types.ObjectId,ref:'User'},name:String,email:String,at:Date,url:String}],
  approvalStatus: { type: String, enum: ['Pending', 'Approved'], default: 'Pending' },
  approvedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
  approvedAt: Date,
  designApprovals:[{_id:false,slot:{type:String,enum:['Creative Head','Art Director']},actor:{type:mongoose.Schema.Types.ObjectId,ref:'User'},name:String,email:String,at:Date}],
  handoffTo: { type: String, enum: ['', 'BP', 'Production', 'Supplier'], default: '' },
  recipientName: { type: String, default: '', maxlength: 120 },
  handedOffAt: Date,
  productionAcceptedAt:Date,
  productionAcceptedBy:{type:mongoose.Schema.Types.ObjectId,ref:'User'},
  productionOrder: { type: mongoose.Schema.Types.ObjectId, ref: 'ProductionOrder' },
  history: [{ action: String, actor: {type: mongoose.Schema.Types.ObjectId, ref:'User'}, actorName: String, actorEmail:String, designDriveUrl:String, at: {type:Date, default:Date.now}, note:String }],
  title: { type: String, required: true, trim: true, maxlength: 160 },
  designerName: { type: String, required: true, trim: true, maxlength: 120 },
  supervisorName: { type: String, required: true, trim: true, maxlength: 120 },
  process: { type: String, enum: ['Planned', 'Designing', 'Review', 'Revision', 'Approved', 'Completed'], default: 'Planned' },
  description: { type: String, default: '', trim: true, maxlength: 2000 },
  ownerName: { type: String, default: '', trim: true, maxlength: 120 },
  reminderEmail: { type: String, default: '', trim: true, lowercase: true, maxlength: 254 },
  dueDate: { type: String, required: true },
  reminderDaysBefore: { type: Number, default: 3, min: 0, max: 90 },
  priority: { type: String, enum: ['Low', 'Medium', 'High', 'Critical'], default: 'High' },
  status: { type: String, enum: ['Planned', 'In Progress', 'Waiting', 'Completed', 'Cancelled'], default: 'Planned' },
  links: [{
    type: { type: String, enum: ['Excel', 'PDF', 'Google Slides'], required: true },
    label: { type: String, default: '', trim: true, maxlength: 120 },
    url: { type: String, required: true, trim: true, maxlength: 1000 }
  }],
  lastReminderSentAt: { type: Date },
  createdBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
  updatedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User' }
}, { timestamps: true, optimisticConcurrency:true });

importantWorkSchema.index({ dueDate: 1, process: 1 });
module.exports = mongoose.model('ImportantWork', importantWorkSchema);
