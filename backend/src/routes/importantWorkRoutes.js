const router = require('express').Router();
const { protect } = require('../middleware/authMiddleware');
const controller = require('../controllers/importantWorkController');
router.use(protect);
const members=require('../controllers/creativeMemberController');
router.get('/members',members.list);
router.post('/members',members.create);
router.put('/members/:memberId',members.update);
router.delete('/members/:memberId',members.remove);
router.get('/contacts',controller.contacts);
router.post('/contacts',controller.addContact);
router.delete('/contacts/:contactId',controller.deleteContact);
router.post('/:id/sent',controller.sent);
router.get('/teams',controller.teams);
router.put('/teams',controller.saveTeams);
router.get('/', controller.list);
router.post('/', controller.create);
router.post('/:id/approve', controller.approve);
router.post('/:id/handoff', controller.handoff);
router.put('/:id', controller.update);
router.delete('/:id', controller.remove);
module.exports = router;
